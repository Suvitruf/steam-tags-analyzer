import { build } from 'esbuild';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../../', import.meta.url);
const result = await build({
  stdin:{contents:`export {unpackGames, selectCohort, summarizeCohort, exposureExclusions, exposureMonths, DEFAULT_FILTER} from './scripts/src/analytics/cohorts';
export {quantile} from './scripts/src/analytics/shared';
export {publisherKey, publisherBucket, portfolioComposition} from './scripts/src/analytics/publishers';
export {selectUpcoming} from './scripts/src/analytics/discovery';`,resolveDir:fileURLToPath(root)},
  bundle:true,write:false,format:'esm',platform:'browser',target:'es2022',
  banner:{js:'// Generated by tools/sync-research.mjs from the shared analytics definitions. Do not edit.'},
});
const path = new URL('src/shared/research-core.js',new URL('../',import.meta.url));
const content=result.outputFiles[0].text;
if(process.argv.includes('--check')) {
  if(await fs.readFile(path,'utf8')!==content) throw Error('Research definitions drifted; run npm run sync:research');
} else await fs.writeFile(path,content);
